"""Keep the app, native targets and signing tools on one explicitly selected App Group.

The identifier is configuration, not a capability grant. Real profiles must authorize it.
"""
import argparse
import json
from pathlib import Path
import plistlib
import re

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "config/app-group.json"
TARGETS = ["src/ControlStudio.App/Platforms/iOS", "native/ControlStudioWidgets", "native/ControlStudioIntents"]


def validate_identifier(identifier):
    if not isinstance(identifier, str) or not re.fullmatch(r"group\.[A-Za-z0-9]+(?:[.-][A-Za-z0-9]+)*", identifier):
        raise ValueError("An explicit App Group identifier beginning with group. is required")
    return identifier


def load_identifier():
    return validate_identifier(json.loads(CONFIG.read_text(encoding="utf-8"))["identifier"])


def generated_files(identifier):
    validate_identifier(identifier)
    result = {
        ROOT / "native/Shared/AppGroupConfiguration.swift":
            ("// Generated by scripts/app_group_config.py. Edit config/app-group.json instead.\n"
             "enum StudioAppGroup {\n"
             f'    static let identifier = "{identifier}"\n'
             "}\n").encode(),
        ROOT / "src/ControlStudio.Core/AppGroupConfiguration.cs":
            ("// Generated by scripts/app_group_config.py. Edit config/app-group.json instead.\n"
             "namespace ControlStudio.Core;\n\n"
             "public static class AppGroupConfiguration\n{\n"
             f'    public const string Identifier = "{identifier}";\n'
             "}\n").encode(),
    }
    for relative in TARGETS:
        folder = ROOT / relative
        result[folder / "Entitlements.plist"] = plistlib.dumps({"com.apple.security.application-groups": [identifier]})
        info = plistlib.loads((folder / "Info.plist").read_bytes())
        info["ControlStudioAppGroup"] = identifier
        result[folder / "Info.plist"] = plistlib.dumps(info)
    return result


def synchronize(check=False):
    for path, content in generated_files(load_identifier()).items():
        if check:
            if not path.is_file() or path.read_bytes().replace(b"\r\n", b"\n") != content:
                raise ValueError(f"App Group configuration drift: {path.relative_to(ROOT)}. Run python scripts/app_group_config.py")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--identifier", help="Explicitly select an App Group authorized by your provider")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.identifier:
        if args.check:
            parser.error("--identifier and --check cannot be combined")
        CONFIG.write_text(json.dumps({"identifier": validate_identifier(args.identifier)}, indent=2) + "\n", encoding="utf-8")
    synchronize(args.check)
    print("App Group configuration " + ("verified: " if args.check else "generated: ") + load_identifier())
