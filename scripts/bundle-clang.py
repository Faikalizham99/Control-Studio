"""Adapt the pinned clang-format ES module exports to a classic, offline WebView script.

Vendor modules stay byte-identical to npm. Only their export keywords are removed
inside one private scope; no eval, dynamic import, CDN or runtime package manager.
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "src/ControlStudio.App/Resources/Raw/Snippets"


def bundle():
    parts = []
    for name in ["clang-format.js", "clang-format-binding.js"]:
        source = (ASSETS / "vendor/clang" / name).read_text(encoding="utf-8")
        source = source.replace("export function ", "function ").replace("export class ", "class ")
        assert "export " not in source and "import " not in source
        parts.append(source)
    adapter = (ROOT / "scripts/clang-adapter.js").read_text(encoding="utf-8")
    return ("// Generated by scripts/bundle-clang.py. See vendor/clang licenses.\n"
            "(() => {\n'use strict';\n"
            "if (!Symbol.dispose) Object.defineProperty(Symbol, 'dispose', { value: Symbol('dispose') });\n"
            + "\n".join(parts) + "\n" + adapter + "\n})();\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ASSETS / "clang-formatter.js"
    source = bundle()
    if args.check:
        assert path.read_text(encoding="utf-8") == source, "Run python scripts/bundle-clang.py"
    else:
        path.write_text(source, encoding="utf-8", newline="\n")
    print("Offline clang-format adapter " + ("verified." if args.check else "generated."))


if __name__ == "__main__":
    main()
